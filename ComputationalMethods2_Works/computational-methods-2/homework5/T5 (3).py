@njit
def random_spins(N):
    spins = np.empty((N, N), dtype=np.int8)
    for i in range(N):
        for j in range(N):
            if np.random.random() < 0.5:
                spins[i, j] = 1
            else:
                spins[i, j] = -1
    return spins


@njit
def energia_total(spins):
    E = 0.0
    N = spins.shape[0]
    for i in range(N):
        for j in range(N):
            E += -spins[i, j] * (spins[(i+1)%N, j] + spins[i, (j+1)%N])
    return E


@njit
def sweep(spins, beta, E):
    N = spins.shape[0]

    for _ in range(N * N):

        i = np.random.randint(0, N)
        j = np.random.randint(0, N)

        s = spins[i, j]

        neighbors = (
            spins[(i+1)%N, j] + spins[(i-1)%N, j] +
            spins[i, (j+1)%N] + spins[i, (j-1)%N]
        )

        dE = 2.0 * s * neighbors

        if dE <= 0 or np.random.random() < np.exp(-beta * dE):
            spins[i, j] = -s
            E += dE

    return E


@njit
def sample_energies(spins, beta, thermal, samples, stride):

    N = spins.shape[0]
    E = energia_total(spins)

    for _ in range(thermal):
        E = sweep(spins, beta, E)

    energies = np.empty(samples)

    for k in range(samples):

        for _ in range(stride):
            E = sweep(spins, beta, E)

        energies[k] = E / (N * N)

    return energies


