alpha = 0.1
xmin, xmax = -20, 20
Nx = 512
dt = 0.001

T = 2*np.pi*5
tmax = 2*T

x = np.linspace(xmin, xmax, Nx)
dx = x[1] - x[0]


psi0 = np.exp(-2*(x-10)**2) * np.exp(-2j*x)
psi0 = psi0 / np.sqrt(np.sum(np.abs(psi0)**2)*dx)


def laplacian(psi):
    return (np.roll(psi,-1) - 2*psi + np.roll(psi,1)) / dx**2

def rhs(psi, V):
    return 1j * (alpha * laplacian(psi) - V * psi)

def step(psi, V):
    k1 = rhs(psi, V)
    k2 = rhs(psi + dt*k1/2, V)
    k3 = rhs(psi + dt*k2/2, V)
    k4 = rhs(psi + dt*k3, V)
    return psi + dt*(k1 + 2*k2 + 2*k3 + k4)/6

def normalize(psi):
    norm = np.sqrt(np.sum(np.abs(psi)**2)*dx)
    return psi/norm

