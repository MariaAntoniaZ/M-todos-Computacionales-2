@njit
def gillespie_critical(n_trajectories, t_max, critical_level, A, B, lambda_U, lambda_Np):

    k = 0

    for _ in range(n_trajectories):

        Y0, Y1, Y2 = 10.0, 10.0, 10.0
        t = 0.0

        while t < t_max:

            tasa0 = A
            tasa1 = lambda_U * Y0
            tasa2 = lambda_Np * Y1
            tasa3 = B * Y2

            total = tasa0 + tasa1 + tasa2 + tasa3

            if total == 0:
                break

            tau = np.random.exponential(1.0 / total)
            t += tau

            r = np.random.rand() * total

            if r < tasa0:
                Y0 += 1
            elif r < tasa0 + tasa1:
                Y0 -= 1; Y1 += 1
            elif r < tasa0 + tasa1 + tasa2:
                Y1 -= 1; Y2 += 1
            else:
                Y2 -= 1

            if Y0 < 0: Y0 = 0
            if Y1 < 0: Y1 = 0
            if Y2 < 0: Y2 = 0

            if Y2 >= critical_level:
                k += 1
                break

    return k


@njit
def sde_critical(n_trajectories, t_max, critical_level, A, B, lambda_U, lambda_Np):

    k = 0
    dt = 0.01

    for _ in range(n_trajectories):

        U, Np, Pu = 10.0, 10.0, 10.0
        t = 0.0

        while t < t_max:

            if Pu >= critical_level:
                k += 1
                break

            W = np.random.normal(0, 1)
            S = 1.0 if np.random.rand() < 0.5 else -1.0

            mu_U = A - lambda_U * U
            sigma_U = np.sqrt(max(0.0, A + lambda_U * U))

            K1_U = dt * mu_U + (W - S) * np.sqrt(dt) * sigma_U
            K2_U = dt * (A - lambda_U * (U + K1_U)) \
                   + (W + S) * np.sqrt(dt) * np.sqrt(max(0.0, A + lambda_U * (U + K1_U)))

            U_new = U + 0.5 * (K1_U + K2_U)

            dNp = (lambda_U * U - lambda_Np * Np) * dt
            dPu = (lambda_Np * Np - B * Pu) * dt

            U = max(0.0, U_new)
            Np += dNp
            Pu += dPu

            t += dt

    return k



from scipy.stats import beta

def estimate_critical_probability(n_trajectories=1000, t_max=30, critical_level=80):

    k_gillespie = gillespie_critical(
        n_trajectories, t_max, critical_level, A, B, lambda_U, lambda_Np
    )

    k_sde = sde_critical(
        n_trajectories, t_max, critical_level, A, B, lambda_U, lambda_Np
    )

    def beta_interval(k, n):
        alpha = 1 + k
        beta_ = 1 + n - k
        p_mean = alpha / (alpha + beta_)
        p_std = np.sqrt((alpha * beta_) / ((alpha + beta_)**2 * (alpha + beta_ + 1)))
        return p_mean * 100, p_std * 100

    p_gillespie, err_gillespie = beta_interval(k_gillespie, n_trajectories)
    p_sde, err_sde = beta_interval(k_sde, n_trajectories)

    with open('3.d.txt', 'w') as f:
        f.write("PROBABILIDAD DE CONCENTRACIÓN CRÍTICA (80 unidades de Pu en 30 días)\n")
        f.write("="*60 + "\n\n")

        f.write(f"Número de trayectorias: {n_trajectories}\n\n")

        f.write("Método Gillespie:\n")
        f.write(f"  Trayectorias que alcanzan criticalidad: {k_gillespie}\n")
        f.write(f"  Probabilidad: {p_gillespie:.2f}% ± {err_gillespie:.2f}%\n\n")

        f.write("Método SDE :\n")
        f.write(f"  Trayectorias que alcanzan criticalidad: {k_sde}\n")
        f.write(f"  Probabilidad: {p_sde:.2f}% ± {err_sde:.2f}%\n\n")

        f.write("Discusión:\n")
        f.write("La probabilidad de alcanzar la concentración crítica es baja en Gillespie y Metropolis.\n")
        f.write("El método de Gillespie tiende a dar valores más conservadores al modelar eventos discretos,\n")
        f.write("mientras que la aproximación SDE puede sobreestimar las fluctuaciones.\n")

    print(f"Gillespie: {p_gillespie:.2f}% ± {err_gillespie:.2f}%")
    print(f"SDE: {p_sde:.2f}% ± {err_sde:.2f}%")