import pde
import numpy as np
import matplotlib.pyplot as plt
from IPython.display import HTML
from matplotlib.animation import FuncAnimation
from tqdm import tqdm

grid = pde.CartesianGrid([[0,5],[0,5]],[200,200])
r_grid = grid.axes_coords[0]
dx = np.diff(r_grid).mean()

np.random.seed(42)

U0 = 1.0 + 0.1*np.random.randn(*grid.shape)
V0 = 1.0 + 0.1*np.random.randn(*grid.shape)

U = pde.ScalarField(grid, data=U0)
V = pde.ScalarField(grid, data=V0)

estado = pde.FieldCollection([U,V])

α = 0.0002
β = 0.06

eq = pde.PDE({
    "u": "α*(d2_dx2(u) + 3*d2_dy2(u)) + u - u**3 - v",
    "v": "β*(d2_dx2(v) + d2_dy2(v)) + 8*(u - v)"
},
consts={"α":α,"β":β},
bc="neumann"
)


D = max(α, β)
dt = 0.4*dx**2/(4*D)
tmax = 30

storage = pde.MemoryStorage()

eq.solve(
    estado,
    t_range=(0, tmax),
    dt=dt,
    tracker=[storage.tracker(0.2)],
    solver="scipy"
)

u_fields = storage.extract_field(0)

fig, ax = plt.subplots(figsize=(6,6))
u_fields[-1].plot(ax=ax, cmap="gray")

ax.set_title(
    f"Zebra stripes\nα={α}, β={β}\nF=u-u³-v\nG=8(u-v)"
)

plt.tight_layout()
plt.savefig("2_zebra_stripes.png", dpi=300)
